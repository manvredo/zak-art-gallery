-- Tasks and monthly goals for the private work plan in the admin area
-- (/admin/arbeitsplan). Only the logged-in admin can read or change them -
-- there is no public policy, so visitors never see the plan.
-- Monthly goals are stored as tasks in the category 'Monatsziele'.
-- Run this once in the Supabase SQL Editor (Project → SQL Editor → New query).

create table if not exists work_tasks (
  id bigint generated by default as identity primary key,
  category text not null,
  text text not null,
  done boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists work_tasks_category_idx on work_tasks (category);

alter table work_tasks enable row level security;

create policy "Work tasks authenticated read"
  on work_tasks for select
  using (auth.role() = 'authenticated');

create policy "Work tasks authenticated insert"
  on work_tasks for insert
  with check (auth.role() = 'authenticated');

create policy "Work tasks authenticated update"
  on work_tasks for update
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

create policy "Work tasks authenticated delete"
  on work_tasks for delete
  using (auth.role() = 'authenticated');

